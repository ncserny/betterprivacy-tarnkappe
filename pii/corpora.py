"""Loaders for human-annotated NER corpora (see scripts/fetch_data.sh).

Every loader returns [(text, [(start, end, label), ...])] with labels PERSON / ORG / LOCATION.

| Corpus            | Text                         | Licence      |
| UNER English EWT  | web: e-mail, reviews, blogs  | CC BY-SA 4.0 |
| UNER German PUD   | news + Wikipedia (test only) | CC BY-SA 4.0 |
| GermEval 2014     | German Wikipedia + news      | CC BY 4.0    |
| WNUT 2017         | social media, forums         | CC BY 4.0    |
| Presidio synth v2 | generated PII sentences      | MIT          |
"""
import json
import os
import random

DATA = os.path.join(os.path.dirname(__file__), "..", "data")

UNER = {"PER": "PERSON", "ORG": "ORG", "LOC": "LOCATION"}
WNUT = {"person": "PERSON", "corporation": "ORG", "group": "ORG", "location": "LOCATION"}


def _sentences(path, tok_col, tag_col):
    toks, tags = [], []
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("# ") or line.startswith("#\t"):
            if toks:
                yield toks, tags
            toks, tags = [], []
            continue
        cols = line.split("\t")
        if len(cols) <= max(tok_col, tag_col):
            continue
        toks.append(cols[tok_col]); tags.append(cols[tag_col])
    if toks:
        yield toks, tags


def _to_example(toks, tags, mapping):
    """Join tokens with spaces and convert BIO tags to character spans."""
    spans, pos, cur = [], 0, None
    for tok, tag in zip(toks, tags):
        typ = mapping.get(tag[2:]) if tag[:2] in ("B-", "I-") else None
        if typ and cur and cur[2] == typ and tag.startswith("I-"):
            cur[1] = pos + len(tok)
        else:
            if cur:
                spans.append(tuple(cur))
            cur = [pos, pos + len(tok), typ] if typ else None
        pos += len(tok) + 1
    if cur:
        spans.append(tuple(cur))
    return " ".join(toks), spans


def _load(path, tok_col, tag_col, mapping):
    return [_to_example(t, g, mapping) for t, g in _sentences(os.path.join(DATA, path), tok_col, tag_col)]


def ewt(split):       return _load(f"UNER_English-EWT/en_ewt-ud-{split}.iob2", 1, 2, UNER)
def pud_de():         return _load("UNER_German-PUD/de_pud-ud-test.iob2", 1, 2, UNER)
def germeval(split):  return _load(f"NER-datasets/GermEval2014/NER-de-{split}.tsv", 1, 2, UNER)


def wnut(split):
    f = {"train": "wnut17train.conll", "dev": "emerging.dev.conll", "test": "emerging.test.annotated"}[split]
    return _load(f"NER-datasets/WNUT17/{f}", 0, 1, WNUT)


def presidio(parity=1):
    """PII test set generated by Microsoft: their templates, their international names and addresses.
    Training renders the even-numbered templates with our own values (data.make_presidio),
    so by default only examples from odd-numbered templates are returned."""
    d = json.load(open(os.path.join(DATA, "presidio-research/synth_dataset_v2.json"), encoding="utf-8"))
    return [(x["full_text"], [(s["start_position"], s["end_position"], s["entity_type"]) for s in x["spans"]])
            for x in d if parity is None or x["template_id"] % 2 == parity]


def join_neighbours(examples, rng: random.Random, max_n=3):
    """Glue 1..max_n consecutive sentences together so the model also sees longer inputs."""
    out, i = [], 0
    while i < len(examples):
        n = rng.choice([1, 1, 2, 3][:max_n + 1])
        text, spans = "", []
        for t, s in examples[i:i + n]:
            off = len(text) + (1 if text else 0)
            text += (" " if text else "") + t
            spans += [(a + off, b + off, l) for a, b, l in s]
        out.append((text, spans))
        i += n
    return out
